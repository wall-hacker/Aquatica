        /// <summary>True if pixel (column, row) of the glyph is lit; row 0 is the top.</summary>
        public static bool IsSet(char c, int column, int row)
        {
            if (!glyphs.TryGetValue(char.ToUpperInvariant(c), out var columns))
                return false;
            return (columns[column] >> row & 1) != 0;
        }

        public static int Measure(string text, int scale = 1) =>
            string.IsNullOrEmpty(text) ? 0 : (text.Length * Advance - 1) * scale;
    }
